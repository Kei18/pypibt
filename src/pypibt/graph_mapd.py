# Validation
# ---------------------------------------------------------------------------

def is_valid_graph_mapd_solution(
    graph: LifGraph,
    starts: list[NodeIdx],
    solution: list[list[NodeIdx]],
    completed_tasks: list[tuple[int, GraphTask]],
    verbose: bool = True,
) -> bool:
    """Validate a LIF MAPD solution.

    Checks:

    1. No vertex collisions (two agents at the same node).
    2. No edge collisions (two agents swapping positions).
    3. All moves are valid (agent moves to an adjacent node or stays).
    4. For each completed task: the assigned agent visited the pickup
       node before the delivery node.

    Args:
        graph: The LIF graph used during the solve.
        starts: Initial node indices, one per agent.
        solution: Per-timestep node lists; ``solution[t][i]`` is the
            ``NodeIdx`` of agent *i* at timestep *t*.
        completed_tasks: List of ``(agent_id, GraphTask)`` pairs from
            ``GraphMAPD.completed_tasks``.
        verbose: If ``True``, print a description of the first error found.

    Returns:
        ``True`` if the solution passes all checks, ``False`` otherwise.
    """
    if not solution:
        if verbose:
            print("Validation Error: empty solution")
        return False

    N = len(starts)
    if list(solution[0]) != list(starts):
        if verbose:
            print("Validation Error: initial configuration does not match starts")
        return False

    adj = graph.adjacency

    for t, config in enumerate(solution):
        for i in range(N):
            v_i = config[i]

            if t > 0:
                v_i_prev = solution[t - 1][i]

                # Valid-move check
                if v_i != v_i_prev and v_i not in adj.get(v_i_prev, []):
                    if verbose:
                        print(
                            f"Validation Error: agent {i} at t={t} made invalid"
                            f" move from {graph.node_ids[v_i_prev]}"
                            f" to {graph.node_ids[v_i]}"
                        )
                    return False

            for j in range(i + 1, N):
                v_j = config[j]

                # Vertex collision
                if v_i == v_j:
                    if verbose:
                        print(
                            f"Validation Error: vertex collision at t={t} â€”"
                            f" agents {i} and {j} both at {graph.node_ids[v_i]}"
                        )
                    return False

                # Edge collision (swap)
                if t > 0:
                    v_i_prev = solution[t - 1][i]
                    v_j_prev = solution[t - 1][j]
                    if v_i == v_j_prev and v_j == v_i_prev:
                        if verbose:
                            print(
                                f"Validation Error: edge collision at t={t} â€”"
                                f" agent {i}: {graph.node_ids[v_i_prev]}â†’{graph.node_ids[v_i]},"
                                f" agent {j}: {graph.node_ids[v_j_prev]}â†’{graph.node_ids[v_j]}"
                            )
                        return False

    # Task-completion check: pickup must precede delivery
    for agent_id, task in completed_tasks:
        t_pickup: int | None = None
        t_delivery: int | None = None

        for t, config in enumerate(solution):
            if config[agent_id] == task.node_pickup and t_pickup is None:
                t_pickup = t
            if config[agent_id] == task.node_delivery:
                t_delivery = t

        if t_pickup is None or t_delivery is None or t_pickup >= t_delivery:
            if verbose:
                print(
                    f"Validation Error: task {task.id} (agent {agent_id})"
                    f" â€” pickup t={t_pickup}, delivery t={t_delivery}"
                )
            return False

    return True

    dirname = os.path.dirname(output_file)
    if dirname:
        os.makedirs(dirname, exist_ok=True)

    def nid(idx: NodeIdx) -> str:
        return graph.node_ids[idx]

    N = len(solution[0]) if solution else 0

    with open(output_file, "w", encoding="utf-8") as f:
        # Header
        f.write(f"agents={N}\n")
        f.write(f"timesteps={len(solution) - 1}\n")
        f.write(f"tasks_completed={stats.get('tasks_completed', len(completed_tasks))}\n")
        f.write(f"tasks_requested={stats.get('tasks_requested', '?')}\n")
        f.write(
            f"total_agent_distance_m={stats.get('total_agent_distance_m', 0.0):.4f}\n"
        )
        f.write(
            f"total_agent_move_steps={stats.get('total_agent_move_steps', 0)}\n"
        )
        f.write(
            f"total_agent_wait_steps={stats.get('total_agent_wait_steps', 0)}\n"
        )
        f.write(
            f"congestion_rate={stats.get('congestion_rate', 0.0):.4f}\n"
        )
        f.write(
            f"avg_used_edge_length_m={stats.get('avg_used_edge_length_m', 0.0):.4f}\n"
        )
        f.write(
            f"avg_slot_duration_s={stats.get('avg_slot_duration_s', 0.0):.6f}\n"
        )
        f.write(
            f"makespan_s={stats.get('makespan_s', 0.0):.4f}\n"
        )
        f.write(
            f"fleet_time_s={stats.get('fleet_time_s', 0.0):.4f}\n"
        )
        f.write(
            f"fleet_utilisation={stats.get('fleet_utilisation', 0.0):.4f}\n"
        )
        f.write(
            f"throughput_tasks_per_m={stats.get('throughput_tasks_per_m', 0.0):.6f}\n"
        )
        f.write(
            f"throughput_tasks_per_slot_m={stats.get('throughput_tasks_per_slot_m', 0.0):.6f}\n"
        )
        f.write(
            f"throughput_tasks_per_s={stats.get('throughput_tasks_per_s', 0.0):.4f}\n"
        )
        f.write(
            f"routing_overhead={stats.get('routing_overhead', 0.0):.4f}\n"
        )

        # Trajectories
        for t, config in enumerate(solution):
            node_str = ",".join(nid(v) for v in config)
            if agent_goals and t < len(agent_goals):
                goal_str = ",".join(
                    f"{nid(g)}:{s}" for g, s in agent_goals[t]
                )
                f.write(f"{t}:{node_str}  # goals:{goal_str}\n")
            else:
                f.write(f"{t}:{node_str}\n")

        # Task log
        if completed_tasks:
            f.write(
                "\n# tasks: id,agent_id,from_station,to_station,"
                "pickup_node,delivery_node,t_appear,t_finished\n"
            )
            for agent_id, task in sorted(completed_tasks, key=lambda x: x[1].id):
                f.write(
                    f"{task.id},{agent_id},{task.station_from},{task.station_to},"
                    f"{nid(task.node_pickup)},{nid(task.node_delivery)},"
                    f"{task.timestep_appear},{task.timestep_finished}\n"
                )
