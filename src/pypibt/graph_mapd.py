def save_graph_mapd_solution(
    graph: LifGraph,
    solution: list[list[NodeIdx]],
    output_file: str,
    completed_tasks: list[tuple[int, GraphTask]] | None = None,
    stats: dict | None = None,
    agent_goals: list[list[tuple[NodeIdx, str]]] | None = None,
) -> None:
    """Save a LIF-MAPD solution to a text file.

    Format::

        agents=N
        timesteps=T
        tasks_completed=K
        tasks_requested=M
        total_agent_distance=D.ddd
        throughput_tasks_per_unit_distance=X.xxx
        0:N1,N7,N15,...
        1:N2,N8,N16,...
        ...
        # tasks: id,agent_id,from_station,to_station,pickup_node,delivery_node,t_appear,t_finished
        0,3,S1,S2,N1,N2,1,45
        ...

    Args:
        graph: The LIF graph (used to convert NodeIdx to node ID strings).
        solution: Per-timestep node-index lists, one entry per agent.
        output_file: Destination file path.
        completed_tasks: List of (agent_id, GraphTask) pairs (optional).
        stats: Statistics dict from ``GraphMAPD.stats`` (optional).
        agent_goals: Per-timestep goal/status lists (optional, written as comments).
    """
    completed_tasks = completed_tasks or []
    stats = stats or {}


