"""Graph MAPD – directed-graph Multi-Agent Pickup and Delivery using PIBT.

Implements MAPD on an arbitrary directed graph loaded from a LIF JSON file.
Tasks are generated by sampling from a transport matrix; each edge is traversed
in exactly one time step regardless of its physical length.  The total distance
driven by each agent is accumulated so that throughput can be normalised by
fleet distance at the end of each run.

Key differences from the grid-based MAPD:
- Node positions are arbitrary (x, y) real-world coordinates, not grid cells.
- Adjacency and distance tables operate on integer node indices (NodeIdx).
- Occupation tables are 1-D numpy arrays indexed by NodeIdx.
- Task pickup / delivery locations are station interaction nodes selected by
  weighted sampling from the transport matrix.
- ``GraphAgent.total_distance`` accumulates the sum of edge lengths traversed.

Dead-end handling:
- A dead-end region is a set of nodes whose only escape route passes through a
  single "entrance node" in the forward direction.  If two agents enter such a
  region simultaneously neither can leave, causing a permanent deadlock.
- ``_detect_dead_ends`` identifies these regions at initialisation time using a
  reverse-reachability analysis: for each node, count how many distinct "exit
  paths" leave the strongly-connected component it belongs to.  Any sub-graph
  reachable only through one gateway is a dead-end.
- ``_locked_entrances`` is recomputed each timestep and returns the set of
  entrance nodes that must be treated as impassable because an agent is already
  inside the corresponding dead-end region.
"""
