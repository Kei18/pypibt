class GraphMAPD:
    """Priority Inheritance with Backtracking for LIF-graph MAPD.

    Mirrors the structure of ``MAPD`` but operates on a directed graph loaded
    from a LIF file.  Agents are placed at random nodes at initialisation.
    Tasks are generated from a weighted transport matrix.

    Each edge is traversed in exactly **one** time step; physical edge lengths
    are summed per agent into ``GraphAgent.total_distance`` and reported in
    ``stats`` after ``run()`` completes.

    Args:
        lif_file: Path to the LIF JSON layout file.
        transport_matrix_file: Path to the transport matrix JSON file.
        num_agents: Number of agents to deploy.
        task_num: Total number of tasks to generate.
        seed: Random seed for agent placement, tie-breaking, and task generation.

    Attributes:
        graph: Parsed LIF graph.
        N: Number of agents.
        starts: Initial node indices for all agents.
        instance: Task-generation instance.
        solution: Per-timestep list of agent node indices (indexed by agent id).
        completed_tasks: List of (agent_id, GraphTask) for finished tasks.
        agent_goals_history: Per-timestep [(goal_node, status), â€¦] for all agents.
        stats: Summary statistics populated at the end of ``run()``.
    """

    def __init__(
        self,
        lif_file: str,
        transport_matrix_file: str,
        num_agents: int,
        task_num: int = 100,
        seed: int = 0,
        task_mode: str = "per_agent",
    ) -> None:
        self.graph = parse_lif(lif_file)
        transport = parse_transport_matrix(transport_matrix_file)

        self.N = num_agents
        self.seed = seed
        self.task_mode = task_mode
        self.rng = np.random.default_rng(seed)

        # Dead-end regions and per-node lookup (computed once at init, needed
        # before start-node selection so the constraint can be applied there).
        self.dead_ends: list[DeadEnd] = _detect_dead_ends(self.graph)
        # Map each interior node to the DeadEnd it belongs to
        self._node_to_dead_end: dict[NodeIdx, DeadEnd] = {
            n: de for de in self.dead_ends for n in de.interior
        }

        self.starts: list[NodeIdx] = self._choose_start_nodes(seed)

        self.instance = GraphMAPDInstance(
            self.graph, transport, task_num, num_agents=self.N, seed=seed, task_mode=task_mode
        )

        # Distance table cache: one GraphDistTable per goal node, allocated lazily
        self._dist_cache: list[GraphDistTable | None] = [None] * self.graph.num_nodes

        # Occupation tables (1-D arrays, indexed by NodeIdx)
        self.NIL: int = self.N  # sentinel: "no agent"
        self.occupied_now = np.full(self.graph.num_nodes, self.NIL, dtype=int)
        self.occupied_next = np.full(self.graph.num_nodes, self.NIL, dtype=int)

        # Solution tracking
        self.solution: list[list[NodeIdx]] = []
        self.completed_tasks: list[tuple[int, GraphTask]] = []
        self.agent_goals_history: list[list[tuple[NodeIdx, str]]] = []
        self.stats: dict = {}

        # Edge usage counter: (from_idx, to_idx) -> number of traversals
        self.edge_usage: dict[tuple[NodeIdx, NodeIdx], int] = {}

    # ------------------------------------------------------------------
    # Public interface
    # ------------------------------------------------------------------

    def run(
        self,
        max_timestep: int = 1000,
        max_comp_time: int = 60_000,
        velocity: float = 1.0,
        stop_before: int = 0,
        warmup_tasks: int = 0,
    ) -> list[list[NodeIdx]]:
        """Run the MAPD simulation.

        Args:
            max_timestep: Hard cap on simulation length.
            max_comp_time: Wall-clock limit in milliseconds.
            velocity: Agent travel speed in m/s (default 1.0).  Used to
                convert distances to physical time in ``stats``.
            stop_before: Stop the simulation when this many tasks are still
                unfinished (i.e., after ``task_num - stop_before`` completions).
                Setting this to approximately ``num_agents`` ensures the system
                is still saturated when metrics are snapshotted, avoiding the
                tail artefact where idle agents skew makespan and waittime.
                Default 0 = run until all tasks are done (original behaviour).
            warmup_tasks: Skip the first *n* task completions from all metrics.
                Allows the fleet to reach a steady spatial distribution before
                measurement starts.  Default 0 = measure from the beginning.

        Returns:
            ``solution[t]`` is a list of ``NodeIdx`` values (one per agent,
            ordered by agent id) at timestep *t*.
        """
        wall_start = time.perf_counter()
        max_wall = max_comp_time / 1000.0

        # Number of completions at which to stop the simulation.
        target_tasks = self.instance.task_num - max(stop_before, 0)

        agents = self._initialize_agents()
        self.solution.append(list(self.starts))
        self._record_goals(agents)
        self.instance.update()

        # Warmup checkpoint: snapshot per-agent counters once warmup_tasks
        # completions are reached.  Pre-initialised to zero so that when
        # warmup_tasks == 0 the subtraction below is a no-op.
        _warmup_ts: int = -1          # timestep at which warmup ended (-1 = no warmup)
        _warmup_n:  int = 0           # tasks completed at warmup end
        _warmup_snap: dict[int, tuple[int, int, float]] = {
            a.id: (0, 0, 0.0) for a in agents
        }
        _warmup_reached: bool = warmup_tasks <= 0

        while self.instance.current_timestep < max_timestep:
            if time.perf_counter() - wall_start >= max_wall:
                print("Computation time limit reached.")
                break

            self._assign_tasks(agents)
            self._plan_agents(agents)
            config = self._execute_actions(agents)
            self.solution.append(config)
            self._update_task_states(agents)
            self._record_goals(agents)
            self.instance.update()

            n_done = len(self.instance.tasks_completed)

            # Record warmup checkpoint the first time we cross the threshold.
            if not _warmup_reached and n_done >= warmup_tasks:
                _warmup_reached = True
                _warmup_ts = self.instance.current_timestep
                _warmup_n  = n_done
                _warmup_snap = {
                    a.id: (a.move_steps, a.wait_steps, a.total_distance)
                    for a in agents
                }

            if n_done >= target_tasks:
                break

        target_reached = len(self.instance.tasks_completed) >= target_tasks
        if self.instance.current_timestep >= max_timestep:
            print(f"Maximum timestep limit reached: {max_timestep}")

        # Compute summary statistics
        # All per-agent counters are adjusted by the warmup snapshot so that
        # the metrics reflect only the measurement window.
        adj_moves = {a.id: a.move_steps    - _warmup_snap[a.id][0] for a in agents}
        adj_waits = {a.id: a.wait_steps    - _warmup_snap[a.id][1] for a in agents}
        adj_dists = {a.id: a.total_distance - _warmup_snap[a.id][2] for a in agents}

        total_dist  = sum(adj_dists.values())
        total_moves = sum(adj_moves.values())
        total_waits = sum(adj_waits.values())

        # Tasks completed within the measurement window (after warmup).
        # Use exact index slicing on self.completed_tasks (which is ordered by
        # completion timestep) so that tasks_done is always exactly
        #   target_tasks - warmup_tasks
        # regardless of how many tasks happen to complete in the same timestep
        # at either boundary.  The timestep-based snapshots for move/wait/
        # distance cannot be made equally exact (they are inherently per-step),
        # but the task-count mismatch they cause is at most Â±1 step's worth of
        # completions â€” negligible for the physical metrics.
        window_completions = self.completed_tasks[warmup_tasks:target_tasks]
        tasks_done = len(window_completions)

        # Per-agent completed task count: from the exact window slice.
        agent_task_counts: dict[int, int] = {a.id: 0 for a in agents}
        for agent_id, _ in window_completions:
            agent_task_counts[agent_id] += 1

        fleet_avg_edge = total_dist / total_moves if total_moves > 0 else 0.0

        # Per-agent physical time (move_time = distance/v; wait_time = waits * own_avg_edge/v)
        agent_move_times_s: list[float] = []
        agent_wait_times_s: list[float] = []
        for a in agents:
            d = adj_dists[a.id]
            m = adj_moves[a.id]
            w = adj_waits[a.id]
            own_avg = (d / m) if m > 0 else fleet_avg_edge
            agent_move_times_s.append(d / velocity)
            agent_wait_times_s.append(w * own_avg / velocity)
        agent_flowtimes_s = [
            agent_move_times_s[a.id] + agent_wait_times_s[a.id] for a in agents
        ]

        makespan_s  = max(agent_flowtimes_s) if agent_flowtimes_s else 0.0
        flowtime_s  = sum(agent_flowtimes_s)
        waittime_s  = sum(agent_wait_times_s)

        makespan_ts = max(adj_moves[a.id] + adj_waits[a.id] for a in agents) if agents else 0
        flowtime_ts = total_moves + total_waits
        waittime_ts = total_waits
        movetime_ts = total_moves

        self.stats = {
            "tasks_completed":    tasks_done,
            "tasks_requested":    self.instance.task_num,
            "warmup_tasks":       warmup_tasks,
            "stop_before":        stop_before,
            "target_reached":     target_reached,
            "tasks_per_agent":    agent_task_counts,
            "num_agents":         self.N,
            "task_mode":          self.instance.task_mode,
            "timesteps":          len(self.solution) - 1,
            # â”€â”€ timestep metrics â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
            "makespan_ts":        makespan_ts,
            "flowtime_ts":        flowtime_ts,
            "waittime_ts":        waittime_ts,
            "congestion_rate_ts": round(waittime_ts / movetime_ts, 4) if movetime_ts > 0 else 0.0,
            # â”€â”€ second metrics (primary) â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
            "makespan_s":         round(makespan_s, 4),
            "flowtime_s":         round(flowtime_s, 4),
            "waittime_s":         round(waittime_s, 4),
            "congestion_rate_s":  round(waittime_s / (flowtime_s - waittime_s), 4) if (flowtime_s - waittime_s) > 0 else 0.0,
            # â”€â”€ distance â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
            "total_distance_m":   round(total_dist, 4),
            "avg_edge_length_m":  round(fleet_avg_edge, 4),
            "velocity_m_per_s":   velocity,
            # â”€â”€ throughput â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
            "throughput_tasks_per_s": round(tasks_done / makespan_s, 4) if makespan_s > 0 else 0.0,
        }

        return self.solution

    def save_solution(self, output_file: str) -> None:
        """Save the solution and statistics to *output_file*."""
        save_graph_mapd_solution(
            self.graph,
            self.solution,
            output_file,
            self.completed_tasks,
            self.stats,
            self.agent_goals_history,
        )

    # ------------------------------------------------------------------
    # Initialisation helpers
    # ------------------------------------------------------------------

    def _choose_start_nodes(self, seed: int) -> list[NodeIdx]:
        """Pick random start nodes, preferring well-connected nodes.

        Enforces that at most one agent starts inside any single dead-end
        corridor, preventing an immediate un-resolvable deadlock at t=0.
        """
        # Prefer nodes with >= 2 outgoing edges to avoid immediate deadlocks
        good = [n for n, nbrs in self.graph.adjacency.items() if len(nbrs) >= 2]
        fallback = [n for n, nbrs in self.graph.adjacency.items() if len(nbrs) >= 1]
        pool = good if len(good) >= self.N else fallback
        if len(pool) < self.N:
            raise ValueError(
                f"Not enough navigable nodes ({len(pool)}) for {self.N} agents"
            )
        rng = random.Random(seed)
        shuffled = pool.copy()
        rng.shuffle(shuffled)

        # Select nodes one by one, skipping any dead-end interior that already
        # has one agent assigned to it.
        chosen: list[NodeIdx] = []
        occupied_dead_ends: set[int] = set()  # dead-end index (id()) of claimed corridors
        for node in shuffled:
            if len(chosen) == self.N:
                break
            de = self._node_to_dead_end.get(node)
            if de is not None:
                de_id = id(de)
                if de_id in occupied_dead_ends:
                    continue  # already one agent in this corridor â€” skip
                occupied_dead_ends.add(de_id)
            chosen.append(node)

        if len(chosen) < self.N:
            raise ValueError(
                f"Not enough valid start nodes ({len(chosen)}) for {self.N} agents "
                f"after enforcing the dead-end corridor constraint"
            )
        return chosen

    def _initialize_agents(self) -> list[GraphAgent]:
        agents: list[GraphAgent] = []
        for i, start in enumerate(self.starts):
            agent = GraphAgent(
                id=i,
                v_now=start,
                v_next=None,
                g=start,
                elapsed=0,
                tie_breaker=float(self.rng.random()),
                task=None,
                target_task=None,
                total_distance=0.0,
                wait_steps=0,
                move_steps=0,
            )
            agents.append(agent)
            self.occupied_now[start] = i
        return agents

    def _record_goals(self, agents: list[GraphAgent]) -> None:
        sorted_agents = sorted(agents, key=lambda a: a.id)
        goals = []
        for agent in sorted_agents:
            if agent.is_assigned():
                status = "A"
            elif agent.is_targeting():
                status = "T"
            else:
                status = "F"
            goals.append((agent.g, status))
        self.agent_goals_history.append(goals)

    # ------------------------------------------------------------------
    # MAPD phases (mirrors mapd.MAPD)
    # ------------------------------------------------------------------

    def _assign_tasks(self, agents: list[GraphAgent]) -> None:
        for agent in agents:
            if agent.is_assigned() or agent.is_targeting():
                continue

            # Agent is free: get next task from the appropriate queue
            if self.instance.task_mode == "global":
                task = self.instance.pop_next_global_task(
                    self.instance.current_timestep
                )
            else:
                task = self.instance.pop_next_task_for_agent(
                    agent.id, self.instance.current_timestep
                )
            if task is None:
                # If idle inside a dead-end corridor, move toward the entrance
                # to clear it; otherwise agents block the corridor indefinitely.
                # Do NOT reset elapsed here â€” accumulated urgency is needed so
                # the agent can win priority ties and actually exit.
                de = self._node_to_dead_end.get(agent.v_now)
                if de is not None:
                    agent.g = de.entrance
                elif agent.v_now == agent.g:
                    # Agent has reached (or is sitting at) its current idle
                    # goal.  Assign a random wander goal so idle agents spread
                    # out across the graph instead of clustering at bottlenecks.
                    # Wandering also grows `elapsed`, giving idle agents
                    # increasing priority to yield when active agents need
                    # their spot via PIBT priority inheritance.
                    # Avoid dead-end interiors to prevent voluntarily locking
                    # a corridor that an active agent needs to use.
                    neighbors = self.graph.adjacency.get(agent.v_now, [])
                    non_de = [n for n in neighbors if n not in self._node_to_dead_end]
                    pool = non_de if non_de else neighbors
                    if pool:
                        agent.g = int(self.rng.choice(pool))
                continue

            if agent.v_now == task.node_pickup:
                # Already at the pickup node â€” go directly to delivery
                self._assign_task(agent, task)
            else:
                agent.target_task = task
                agent.g = task.node_pickup

    def _assign_task(self, agent: GraphAgent, task: GraphTask) -> None:
        agent.task = task
        agent.target_task = None
        task.assigned = True
        agent.g = task.node_delivery

    def _plan_agents(self, agents: list[GraphAgent]) -> None:
        self.occupied_next.fill(self.NIL)
        agent_list: list[GraphAgent | None] = [None] * len(agents)
        for agent in agents:
            agent_list[agent.id] = agent

        # Anti-livelock: agents stuck for a long time without reaching their
        # goal get a fresh random tie-breaker so the priority ordering is
        # perturbed and stable cycling patterns are broken.
        # Threshold of 200 steps is well above the longest legitimate routing
        # distance on our maps; genuine livelocks accumulate elapsed >> 200.
        for agent in agents:
            if agent.elapsed > 200:
                agent.tie_breaker = float(self.rng.random())

        agents.sort(key=self._priority_key, reverse=True)

        locked = self._locked_entrances(agents)

        for agent in agents:
            if agent.v_next is None:
                self._func_pibt(agent, agent_list, locked_entrances=locked)

    def _execute_actions(self, agents: list[GraphAgent]) -> list[NodeIdx]:
        # Two-pass update to avoid clearing a newly-set position
        for agent in agents:
            self.occupied_now[agent.v_now] = self.NIL
            if agent.v_next is not None:
                self.occupied_next[agent.v_next] = self.NIL

        for agent in agents:
            prev = agent.v_now
            agent.v_now = agent.v_next  # type: ignore[assignment]
            self.occupied_now[agent.v_now] = agent.id

            if agent.v_now != prev:
                edge_len = self.graph.edge_lengths.get((prev, agent.v_now), 0.0)
                agent.total_distance += edge_len
                agent.move_steps += 1
                self.edge_usage[(prev, agent.v_now)] = (
                    self.edge_usage.get((prev, agent.v_now), 0) + 1
                )
            else:
                agent.wait_steps += 1

            agent.elapsed = 0 if agent.v_now == agent.g else agent.elapsed + 1
            agent.v_next = None

        return [a.v_now for a in sorted(agents, key=lambda a: a.id)]

    def _update_task_states(self, agents: list[GraphAgent]) -> None:
        for agent in agents:
            if agent.is_assigned():
                if agent.v_now == agent.task.node_delivery:
                    agent.task.timestep_finished = self.instance.current_timestep
                    self.instance.tasks_assigned.remove(agent.task)
                    self.instance.tasks_completed.append(agent.task)
                    self.completed_tasks.append((agent.id, agent.task))
                    agent.task = None
                    agent.target_task = None
                    agent.g = agent.v_now
                    agent.elapsed = 0

            elif agent.is_targeting():
                if agent.v_now == agent.target_task.node_pickup:
                    self._assign_task(agent, agent.target_task)

    def _func_pibt(
        self,
        agent: GraphAgent,
        agent_list: list[GraphAgent | None],
        calling_agent: GraphAgent | None = None,
        locked_entrances: frozenset[NodeIdx] | None = None,
    ) -> bool:
        """Core PIBT step for one agent.

        ``locked_entrances`` is an optional set of nodes that must not be
        entered by any agent that is not already inside the corresponding
        dead-end region.  This prevents two agents from occupying a dead-end
        simultaneously and causing an irrecoverable deadlock.
        """
        neighbors = self.graph.adjacency.get(agent.v_now, [])
        candidates = neighbors + [agent.v_now]

        # Sort candidates: closer to goal first; prefer occupied over empty
        # when distances are tied (keeps traffic moving).
        # Exception: when an agent has been stuck for a very long time
        # (deep livelock), randomise the candidate order so it tries a
        # different direction and can escape the cycling pattern.
        if agent.elapsed > 200:
            idxs = self.rng.permutation(len(candidates))
            candidates = [candidates[int(i)] for i in idxs]
        else:
            keyed = []
            for v in candidates:
                d = self._get_path_dist(v, agent.g)
                is_empty = 1 if int(self.occupied_now[v]) == self.NIL else 0
                keyed.append((v, d, is_empty))
            keyed.sort(key=lambda x: (x[1], x[2]))
            candidates = [v for v, _, _ in keyed]

        for u in candidates:
            if int(self.occupied_next[u]) != self.NIL:
                continue
            if calling_agent is not None and u == calling_agent.v_now:
                continue

            # Dead-end entrance guard ----------------------------------------
            # At most one agent may be inside a dead-end corridor at a time.
            # While any agent occupies the interior, the entrance node and
            # all interior nodes are blocked for agents currently outside.
            # Interior agents run at tier-3 (highest priority) and are planned
            # first, so they claim occupied_next[entrance] before any outer
            # agent.  The protected fallback ensures no outer agent overwrites
            # that reservation.  Agents already inside are free to exit.
            if locked_entrances:
                blocked = False
                for de in self.dead_ends:
                    if de.entrance not in locked_entrances:
                        continue
                    if agent.v_now in de.interior:
                        break  # already inside -- free to move anywhere
                    if u == de.entrance or u in de.interior:
                        blocked = True
                        break
                if blocked:
                    continue
            # ----------------------------------------------------------------

            ak_id = int(self.occupied_now[u])
            self.occupied_next[u] = agent.id
            agent.v_next = u

            if ak_id != self.NIL and ak_id != agent.id:
                ak = agent_list[ak_id]
                if ak is not None and ak.v_next is None:
                    # Priority inheritance: plan for the blocking agent first.
                    # If it fails, release our stale reservation on u so other
                    # agents are not misled into thinking u is taken.
                    if not self._func_pibt(ak, agent_list, agent, locked_entrances):
                        self.occupied_next[u] = self.NIL
                        agent.v_next = None
                        continue

            return True

        # No valid move found: stay in place.
        # Only write if the slot is genuinely free â€” a higher-priority agent
        # (e.g. tier-3 interior agent) may have already claimed this node.
        # Overwriting that reservation corrupts its planned exit and causes
        # permanent gridlock.  We still set v_next = v_now so the agent is
        # counted as waiting; execute_actions handles the collision gracefully
        # (higher-priority agent's v_now update wins in occupied_now).
        if int(self.occupied_next[agent.v_now]) == self.NIL:
            self.occupied_next[agent.v_now] = agent.id
        agent.v_next = agent.v_now
        return False

    def _get_path_dist(self, start: NodeIdx, goal: NodeIdx) -> int:
        if self._dist_cache[goal] is None:
            self._dist_cache[goal] = GraphDistTable(
                self.graph.rev_adjacency, self.graph.num_nodes, goal
            )
        return self._dist_cache[goal].get(start)

    def _priority_key(self, agent: GraphAgent) -> tuple:
        # Agents currently inside a dead-end corridor get the highest tier so
        # they are planned before anyone else can fill occupied_next[entrance]
        # via a fallback stay.  This guarantees an uncontested exit path.
        if agent.v_now in self._node_to_dead_end:
            tier = 3
        elif agent.is_assigned():
            tier = 2
        elif agent.is_targeting():
            tier = 1
        else:
            tier = 0
        return (tier, agent.elapsed, agent.tie_breaker)

    def _locked_entrances(self, agents: list[GraphAgent]) -> frozenset[NodeIdx]:
        """Return dead-end entrance nodes that must be blocked this timestep.

        An entrance is locked when at least one agent is already inside that
        dead-end's interior, preventing a second agent from entering.
        For bidirectional corridors both entrances are locked.
        """
        if not self.dead_ends:
            return frozenset()
        occupied_interior: set[NodeIdx] = {
            a.v_now for a in agents if a.v_now in self._node_to_dead_end
        }
        locked: set[NodeIdx] = set()
        for de in self.dead_ends:
            if de.interior & occupied_interior:
                locked.add(de.entrance)
                if de.entrance2 != -1:
                    locked.add(de.entrance2)
        return frozenset(locked)


# ---------------------------------------------------------------------------
# Dead-end detection
# ---------------------------------------------------------------------------

def _detect_dead_ends(graph: LifGraph) -> list[DeadEnd]:
    """Detect dead-end corridors in the directed graph.

    Algorithm:

    1. Find all *tip* nodes â€” nodes with exactly **1 outgoing edge**.
    2. From each tip, trace forward: if the next node has exactly **2
       outgoing edges** it is part of the corridor interior.  Continue
       until a node with **3 or more outgoing edges** is reached â€” that
       node is the corridor *entrance*.
    3. The interior is all nodes from the tip up to (but not including)
       the entrance.  While any agent occupies the interior the entrance
       is blocked, preventing a second agent from entering and causing a
       deadlock.

    Returns:
        List of :class:`DeadEnd` objects (empty if the graph has none).
    """
    adj = graph.adjacency
    dead_ends: list[DeadEnd] = []
    seen_interiors: set[frozenset[NodeIdx]] = set()

    for tip in range(graph.num_nodes):
        if len(adj.get(tip, [])) != 1:
            continue

        # Trace forward from the tip along corridor nodes
        interior: list[NodeIdx] = [tip]
        interior_set: set[NodeIdx] = {tip}
        current: NodeIdx = tip
        entrance: NodeIdx = -1

        while True:
            nexts = [w for w in adj.get(current, []) if w not in interior_set]
            if not nexts:
                break  # no forward exit from this node
            nxt = nexts[0]
            nxt_out = len(adj.get(nxt, []))
            if nxt_out >= 3:
                entrance = nxt
                break
            elif nxt_out == 2:
                interior.append(nxt)
                interior_set.add(nxt)
                current = nxt
            else:
                # Another tip or isolated node â€” no valid entrance
                break

        if entrance == -1:
            continue  # no valid entrance found for this tip

        key = frozenset(interior_set)
        if key in seen_interiors:
            continue
        seen_interiors.add(key)
        dead_ends.append(DeadEnd(entrance=entrance, interior=key))

    return dead_ends


