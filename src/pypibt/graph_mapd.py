class GraphMAPDInstance:
    """Per-agent pre-assigned task queues driven by a transport matrix.

    All tasks are generated at initialisation time using ``seed``, then
    distributed round-robin across agents so that each agent receives an
    **equal-length** task list.  If ``task_num`` is not divisible by
    ``num_agents`` it is silently rounded up to the next multiple.

    Round-robin interleaving preserves the station-flow ratio across every
    agentâ€™s sub-list because the global list is already flow-weighted.
    Each agent always picks up the next task from *its own* queue when it
    becomes free, eliminating proximity-based assignment bias and making
    results reproducible and comparable across different graphs.

    Attributes:
        graph: The LIF graph.
        transport_matrix: Material flow specification.
        num_agents: Number of agents (determines queue count and queue length).
        task_num: Total tasks (rounded up to ``num_agents`` Ã— ``tasks_per_agent``).
        tasks_per_agent: Tasks in each agentâ€™s queue (equal for all agents).
        current_timestep: Current simulation step.
        agent_task_queues: Per-agent ordered task lists (indexed by agent id).
        tasks_assigned: Tasks currently in progress.
        tasks_completed: Delivered tasks.
    """

    def __init__(
        self,
        graph: LifGraph,
        transport_matrix: TransportMatrix,
        task_num: int,
        num_agents: int,
        seed: int = 0,
        task_mode: str = "per_agent",
    ) -> None:
        if task_mode not in ("per_agent", "global"):
            raise ValueError(f"task_mode must be 'per_agent' or 'global', got {task_mode!r}")
        self.graph = graph
        self.transport_matrix = transport_matrix
        self.num_agents = num_agents
        self.seed = seed
        self.task_mode = task_mode

        # Distribute task_num exactly: no rounding.
        # In per_agent mode, agents 0..(remainder-1) get one extra task.
        self.tasks_per_agent: int = task_num // num_agents
        self.task_num: int = task_num

        self.current_timestep: int = 0
        self.tasks_assigned: list[GraphTask] = []
        self.tasks_completed: list[GraphTask] = []

        # Validate stations
        for from_s, to_s, _ in transport_matrix.flows:
            if from_s not in graph.station_nodes:
                raise ValueError(
                    f"Station '{from_s}' from transport matrix not found in LIF file"
                )
            if to_s not in graph.station_nodes:
                raise ValueError(
                    f"Station '{to_s}' from transport matrix not found in LIF file"
                )

        self._flow_pairs = [(f, t) for f, t, _ in transport_matrix.flows]
        self._flow_weights = [q for _, _, q in transport_matrix.flows]

        # Generate all tasks then distribute according to task_mode
        all_tasks = self._pregenerate_tasks()
        if task_mode == "per_agent":
            # Round-robin interleaving: each agent receives tasks at positions
            # i, i+num_agents, i+2*num_agents, â€¦ so agents with id <
            # (task_num % num_agents) naturally receive one extra task.
            self.agent_task_queues: list[list[GraphTask]] = [
                [all_tasks[j] for j in range(i, self.task_num, num_agents)]
                for i in range(num_agents)
            ]
            self.global_task_queue: list[GraphTask] = []
        else:  # "global"
            self.agent_task_queues = [[] for _ in range(num_agents)]
            self.global_task_queue = list(all_tasks)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _sample_task(
        self, rng: random.Random
    ) -> tuple[NodeIdx, NodeIdx, str, str]:
        """Sample one (pickup_node, delivery_node, from_station, to_station)."""
        idx = rng.choices(
            range(len(self._flow_pairs)), weights=self._flow_weights
        )[0]
        from_station, to_station = self._flow_pairs[idx]

        pickup_nodes = self.graph.station_nodes[from_station]
        delivery_nodes = self.graph.station_nodes[to_station]

        pickup_node = rng.choice(pickup_nodes)
        delivery_node = rng.choice(delivery_nodes)

        # Avoid identical pickup and delivery when alternatives exist
        if pickup_node == delivery_node and len(delivery_nodes) > 1:
            alternatives = [n for n in delivery_nodes if n != pickup_node]
            delivery_node = rng.choice(alternatives)

        return pickup_node, delivery_node, from_station, to_station

    def _pregenerate_tasks(self) -> list[GraphTask]:
        """Generate the full ordered task list using the configured seed."""
        rng = random.Random(self.seed)
        tasks: list[GraphTask] = []
        for i in range(self.task_num):
            pickup, delivery, from_s, to_s = self._sample_task(rng)
            tasks.append(
                GraphTask(
                    id=i,
                    node_pickup=pickup,
                    node_delivery=delivery,
                    station_from=from_s,
                    station_to=to_s,
                    timestep_appear=0,  # set when popped
                    timestep_finished=None,
                    assigned=False,
                )
            )
        return tasks

    # ------------------------------------------------------------------
    # Public interface
    # ------------------------------------------------------------------

    def pop_next_task_for_agent(
        self, agent_id: int, current_timestep: int
    ) -> GraphTask | None:
        """Pop and return the next task from *agent_id*â€™s queue.

        Returns ``None`` when that agentâ€™s queue is exhausted.
        The taskâ€™s ``timestep_appear`` is set to *current_timestep*.
        """
        queue = self.agent_task_queues[agent_id]
        if not queue:
            return None
        task = queue.pop(0)
        task.timestep_appear = current_timestep
        self.tasks_assigned.append(task)
        return task

    def pop_next_global_task(self, current_timestep: int) -> GraphTask | None:
        """Pop the next task from the shared global FIFO queue.

        Returns ``None`` when the global queue is exhausted.
        Used when ``task_mode == "global"``.
        """
        if not self.global_task_queue:
            return None
        task = self.global_task_queue.pop(0)
        task.timestep_appear = current_timestep
        self.tasks_assigned.append(task)
        return task

    def update(self) -> None:
        """Advance the internal timestep counter by one."""
        self.current_timestep += 1


