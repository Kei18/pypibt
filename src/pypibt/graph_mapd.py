@dataclass
class DeadEnd:
    """A dead-end or single-lane corridor in the directed graph.

    Represents a region of nodes that can only be traversed single-file.
    When any agent occupies the interior, all entrance nodes are locked so
    that no additional agent may enter and cause a head-on deadlock.

    Attributes:
        entrance: The single gateway node (or one of two for a bidirectional
            corridor) through which agents must pass to enter the region.
            For bidirectional corridors a second entrance is stored in
            ``entrance2`` (may be ``-1`` if there is only one entrance).
        interior: All nodes strictly inside the dead-end or corridor.
            When any agent is on one of these nodes the entrance(s) are locked.
        entrance2: Second entrance for bidirectional corridors (``-1`` if none).
    """

    entrance: NodeIdx
    interior: frozenset[NodeIdx]
    entrance2: NodeIdx = -1  # -1 means single-entrance dead-end


@dataclass
class GraphTask:
    """Pickup-and-delivery task defined by station interaction nodes.

    Attributes:
        id: Unique task identifier.
        node_pickup: NodeIdx of the pickup location (station interaction node).
        node_delivery: NodeIdx of the delivery location.
        station_from: Source station ID (e.g. "S1").
        station_to: Destination station ID (e.g. "S2").
        timestep_appear: Simulation step at which the task became available.
        timestep_finished: Step at which the task was delivered (None if open).
        assigned: True once an agent has picked up the item.
    """

    id: int
    node_pickup: NodeIdx
    node_delivery: NodeIdx
    station_from: str
    station_to: str
    timestep_appear: int
    timestep_finished: int | None
    assigned: bool

    def is_completed(self) -> bool:
        return self.timestep_finished is not None


@dataclass
class GraphAgent:
    """Agent for LIF-graph MAPD.

    Same lifecycle as ``mapd.Agent`` (free â†’ targeting â†’ assigned) but uses
    ``NodeIdx`` for position and accumulates physical distance.

    Attributes:
        id: Agent index (0 â€¦ N-1).
        v_now: Current node index.
        v_next: Planned next node index; None until planning is complete.
        g: Current goal node index.
        elapsed: Steps since the agent last reached its goal (priority counter).
        tie_breaker: Random float for deterministic priority tie-breaking.
        task: Active assigned task (carrying to delivery); None if not carrying.
        target_task: Task being targeted (en-route to pickup); None otherwise.
        total_distance: Cumulative sum of edge lengths traversed this run.
        wait_steps: Number of timesteps the agent stayed in place (no move).
        move_steps: Number of timesteps the agent actually moved.
    """

    id: int
    v_now: NodeIdx
    v_next: NodeIdx | None
    g: NodeIdx
    elapsed: int
    tie_breaker: float
    task: GraphTask | None
    target_task: GraphTask | None
    total_distance: float
    wait_steps: int
    move_steps: int

    def is_assigned(self) -> bool:
        return self.task is not None

    def is_targeting(self) -> bool:
        return self.target_task is not None

    def is_free(self) -> bool:
        return self.task is None and self.target_task is None


